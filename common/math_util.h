static inline float math_sin(float radians) {
    // Convert radians to table index
    float degrees = radians * 57.2957795f;  // 180/PI
    int idx = ((int)degrees % 360 + 360) % 360;
    int table_idx = (idx * 256) / 360;
    return sin_table[table_idx & 0xFF];
}

static inline float math_cos(float radians) {
    // cos(x) = sin(x + PI/2)
    return math_sin(radians + 1.5707963f);
}

